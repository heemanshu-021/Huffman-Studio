import React, { useState, useRef, DragEvent, ChangeEvent } from 'react';
import {
  FileText,
  FileCheck,
  X,
  Download,
  Copy,
  Check,
  AlertTriangle,
  Hash,
  ShieldCheck,
  Cpu,
  UploadCloud,
} from 'lucide-react';
import { decompressionService } from '../services/decompressionService';
import { useSessionStats } from '../hooks/useSessionStats';
import { useToast } from '../components/ui/Toast';
import { DecompressionResult } from '../types/compression';
import { formatBytes } from '../utils/formatters';
import { StepIndicator } from '../components/ui/StepIndicator';
import { MetricCard } from '../components/ui/MetricCard';
import { Button } from '../components/ui/Button';
import { Badge } from '../components/ui/Badge';

const STEPS = [
  { label: 'Select .huf', description: 'Upload archive' },
  { label: 'Decompress', description: 'Restore content' },
  { label: 'Review', description: 'Download text' },
];

export const DecompressorPage: React.FC = () => {
  const [selectedFile, setSelectedFile] = useState<File | null>(null);
  const [isDragging, setIsDragging] = useState(false);
  const [isDecompressing, setIsDecompressing] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<DecompressionResult | null>(null);
  const [isCopied, setIsCopied] = useState(false);

  const fileInputRef = useRef<HTMLInputElement>(null);
  const { recordOperation } = useSessionStats();
  const toast = useToast();

  const currentStep = result ? 2 : selectedFile ? 1 : 0;

  const handleDragOver = (e: DragEvent<HTMLDivElement>) => {
    e.preventDefault();
    setIsDragging(true);
  };
  const handleDragLeave = (e: DragEvent<HTMLDivElement>) => {
    e.preventDefault();
    setIsDragging(false);
  };

  const validateAndSetFile = (file: File) => {
    setError(null);
    setResult(null);
    if (!file.name.toLowerCase().endsWith('.huf')) {
      setError('Please select a valid .huf archive file generated by Huffman Studio.');
      return;
    }
    setSelectedFile(file);
  };

  const handleDrop = (e: DragEvent<HTMLDivElement>) => {
    e.preventDefault();
    setIsDragging(false);
    if (e.dataTransfer.files?.length) validateAndSetFile(e.dataTransfer.files[0]);
  };

  const handleFileChange = (e: ChangeEvent<HTMLInputElement>) => {
    if (e.target.files?.length) validateAndSetFile(e.target.files[0]);
  };

  const clearSelection = () => {
    setSelectedFile(null);
    setError(null);
    setResult(null);
    setIsCopied(false);
    if (fileInputRef.current) fileInputRef.current.value = '';
  };

  const handleDecompress = async () => {
    if (!selectedFile) return;
    setIsDecompressing(true);
    setError(null);
    try {
      const res = await decompressionService.decompressFile(selectedFile);
      setResult(res);
      recordOperation({
        type: 'DECOMPRESS',
        fileName: selectedFile.name,
        originalSize: res.blob.size,
        processedSize: selectedFile.size,
        ratio: res.stats?.compressionRatio,
        savingsPercent: res.stats?.percentageSaved,
      });
      toast.success('Archive restored!', `${res.filename} is ready.`);
    } catch (err: unknown) {
      const msg =
        err instanceof Error ? err.message : 'Failed to decompress archive. The file may be corrupt.';
      setError(msg);
      toast.error('Decompression failed', msg);
    } finally {
      setIsDecompressing(false);
    }
  };

  const handleCopyToClipboard = async () => {
    if (!result) return;
    try {
      await navigator.clipboard.writeText(result.text);
      setIsCopied(true);
      toast.success('Copied to clipboard');
      setTimeout(() => setIsCopied(false), 2000);
    } catch {
      toast.error('Copy failed', 'Could not access clipboard.');
    }
  };

  const handleDownloadText = () => {
    if (!result) return;
    decompressionService.downloadBlob(result.blob, result.filename);
  };

  return (
    <div className="space-y-6 animate-fade-in">
      {/* Header */}
      <div>
        <div className="flex items-center gap-2.5 mb-1">
          <FileText className="w-5 h-5 text-emerald-400" />
          <h2 className="text-xl font-bold text-slate-100">Archive Decompressor</h2>
        </div>
        <p className="text-sm text-slate-400">
          Upload previously generated{' '}
          <code className="text-emerald-400 font-mono text-xs">.huf</code> archives to reconstruct
          the exact original text with bit-for-bit CRC-32 validation.
        </p>
      </div>

      {/* Step indicator */}
      <StepIndicator steps={STEPS} currentStep={currentStep} className="max-w-lg" />

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Main column */}
        <div className="lg:col-span-2 space-y-5">
          {/* Upload card */}
          <div className="rounded-xl border border-slate-800/80 bg-[#14141c] p-5">
            <input
              type="file"
              ref={fileInputRef}
              onChange={handleFileChange}
              accept=".huf"
              className="hidden"
            />

            {!selectedFile ? (
              <div
                onDragOver={handleDragOver}
                onDragLeave={handleDragLeave}
                onDrop={handleDrop}
                onClick={() => fileInputRef.current?.click()}
                className={`border-2 border-dashed rounded-xl p-10 text-center cursor-pointer transition-all ${
                  isDragging
                    ? 'border-emerald-400 bg-emerald-500/8 scale-[1.01]'
                    : 'border-slate-700 hover:border-emerald-500/50 hover:bg-slate-900/40'
                }`}
              >
                <UploadCloud
                  className={`w-10 h-10 mx-auto mb-3 transition-colors ${
                    isDragging ? 'text-emerald-400' : 'text-slate-600'
                  }`}
                />
                <h3 className="text-sm font-semibold text-slate-200">
                  {isDragging ? 'Drop .huf archive here' : 'Select .huf archive to decompress'}
                </h3>
                <p className="text-xs text-slate-500 mt-1 mb-5">
                  Reconstructs original tree topology and decodes stream with BitReader
                </p>
                <Button variant="primary" size="sm">
                  Select .huf File
                </Button>
              </div>
            ) : (
              <div className="space-y-5">
                <div className="flex items-center justify-between p-3.5 rounded-xl bg-slate-900/60 border border-slate-700/50">
                  <div className="flex items-center gap-3 min-w-0">
                    <div className="w-9 h-9 rounded-lg bg-emerald-500/10 border border-emerald-500/20 flex items-center justify-center text-emerald-400 flex-shrink-0">
                      <FileCheck className="w-4 h-4" />
                    </div>
                    <div className="min-w-0">
                      <p className="text-sm font-semibold text-slate-100 truncate">
                        {selectedFile.name}
                      </p>
                      <p className="text-xs text-slate-500 font-mono">
                        {formatBytes(selectedFile.size)} · Huffman Binary Archive
                      </p>
                    </div>
                  </div>
                  <button
                    onClick={clearSelection}
                    disabled={isDecompressing}
                    className="p-1.5 rounded-lg text-slate-500 hover:text-rose-400 hover:bg-slate-800 transition-colors disabled:opacity-40"
                    aria-label="Remove file"
                  >
                    <X className="w-4 h-4" />
                  </button>
                </div>

                <Button
                  variant="primary"
                  size="lg"
                  onClick={handleDecompress}
                  disabled={isDecompressing}
                  loading={isDecompressing}
                  leftIcon={<FileText className="w-4 h-4" />}
                  className="w-full"
                >
                  {isDecompressing ? 'Decompressing Archive…' : 'Decompress Archive'}
                </Button>
              </div>
            )}

            {error && (
              <div className="mt-4 p-3.5 rounded-xl bg-rose-950/40 border border-rose-800/50 flex items-start gap-3">
                <AlertTriangle className="w-4 h-4 text-rose-400 flex-shrink-0 mt-0.5" />
                <div>
                  <p className="text-xs font-semibold text-rose-200">Decompression Failure</p>
                  <p className="text-xs text-rose-300 mt-0.5 leading-relaxed">{error}</p>
                </div>
              </div>
            )}
          </div>

          {/* Results card */}
          {result && (
            <div className="rounded-xl border border-emerald-500/20 bg-[#14141c] p-5 space-y-5 animate-fade-in">
              <div className="flex items-center justify-between flex-wrap gap-3">
                <div className="flex items-center gap-2">
                  <ShieldCheck className="w-4 h-4 text-emerald-400" />
                  <h3 className="text-sm font-semibold text-slate-100">Restored Content</h3>
                  <Badge variant="emerald" dot className="ml-1">
                    CRC-32 Verified
                  </Badge>
                </div>
                <div className="flex items-center gap-2">
                  <Button
                    variant="secondary"
                    size="sm"
                    onClick={handleCopyToClipboard}
                    leftIcon={
                      isCopied ? (
                        <Check className="w-3.5 h-3.5 text-emerald-400" />
                      ) : (
                        <Copy className="w-3.5 h-3.5" />
                      )
                    }
                  >
                    {isCopied ? 'Copied!' : 'Copy Text'}
                  </Button>
                  <Button
                    variant="primary"
                    size="sm"
                    onClick={handleDownloadText}
                    leftIcon={<Download className="w-3.5 h-3.5" />}
                  >
                    Download .txt
                  </Button>
                </div>
              </div>

              {/* Stats */}
              <div className="grid grid-cols-2 sm:grid-cols-3 gap-3">
                <MetricCard
                  label="Restored Size"
                  value={formatBytes(result.blob.size)}
                  accent="slate"
                />
                <MetricCard
                  label="Characters"
                  value={result.text.length.toLocaleString()}
                  sub="Unicode code points"
                  accent="emerald"
                />
                <MetricCard
                  label="Integrity"
                  value="Verified ✓"
                  sub="CRC-32 IEEE 802.3"
                  accent="emerald"
                />
              </div>

              {/* Text preview */}
              <div className="space-y-2">
                <label className="text-xs font-semibold uppercase tracking-wider text-slate-500">
                  Recovered Text Preview
                </label>
                <textarea
                  readOnly
                  rows={12}
                  value={result.text}
                  className="w-full rounded-xl bg-slate-950 border border-slate-700/80 p-4 font-mono text-xs text-slate-200 leading-relaxed focus:outline-none focus:ring-1 focus:ring-emerald-500/50 resize-y"
                  aria-label="Recovered text content"
                />
              </div>
            </div>
          )}
        </div>

        {/* Right column */}
        <div className="space-y-5">
          <div className="rounded-xl border border-slate-800/80 bg-[#14141c] p-5 space-y-4">
            <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-500">
              Integrity Guarantees
            </h4>
            <div className="space-y-4 text-xs">
              {[
                {
                  icon: <ShieldCheck className="w-4 h-4 text-emerald-400" />,
                  title: 'CRC-32 Verification',
                  desc: 'The Java backend re-computes CRC-32 of the decompressed bytes and verifies against the 4-byte checksum embedded in the header.',
                },
                {
                  icon: <Hash className="w-4 h-4 text-emerald-400" />,
                  title: 'Topology Reconstruction',
                  desc: 'The serialized preorder tree sequence is traversed to rebuild the exact Huffman tree without the original frequency table.',
                },
                {
                  icon: <Cpu className="w-4 h-4 text-emerald-400" />,
                  title: 'Full Unicode Fidelity',
                  desc: 'Supports 1–4 byte UTF-8 sequences including multi-lingual alphabets, CJK, emojis, and symbols.',
                },
              ].map((item) => (
                <div key={item.title} className="flex items-start gap-3">
                  <span className="flex-shrink-0 mt-0.5">{item.icon}</span>
                  <div>
                    <p className="font-semibold text-slate-200">{item.title}</p>
                    <p className="text-slate-500 mt-0.5 leading-relaxed">{item.desc}</p>
                  </div>
                </div>
              ))}
            </div>
          </div>

          <div className="rounded-xl border border-slate-800/80 bg-[#14141c] p-5 space-y-3">
            <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-500">
              Error Diagnostics
            </h4>
            <p className="text-xs text-slate-500">
              The backend rejects invalid archives with precise error codes:
            </p>
            <ul className="space-y-1.5 text-[11px] font-mono">
              {[
                ['INVALID_ARCHIVE_MAGIC', 'Not a .huf file'],
                ['UNSUPPORTED_VERSION', 'Incompatible version'],
                ['CHECKSUM_MISMATCH', 'File modified or corrupted'],
                ['CORRUPTED_ARCHIVE', 'Truncated bitstream'],
              ].map(([code, desc]) => (
                <li key={code} className="flex items-start gap-2">
                  <code className="text-rose-400 flex-shrink-0">{code}</code>
                  <span className="text-slate-500">— {desc}</span>
                </li>
              ))}
            </ul>
          </div>
        </div>
      </div>
    </div>
  );
};

import React, { useState, useRef, DragEvent, ChangeEvent } from 'react';
import { Card } from '../components/Card';
import { decompressionService } from '../services/decompressionService';
import { useSessionStats } from '../hooks/useSessionStats';
import { DecompressionResult } from '../types/compression';
import { formatBytes } from '../utils/formatters';
import {
  FileText,
  FileCheck,
  X,
  Download,
  Copy,
  Check,
  AlertTriangle,
  Loader2,
  Hash,
  ShieldCheck,
  Cpu,
} from 'lucide-react';

export const DecompressorPage: React.FC = () => {
  const [selectedFile, setSelectedFile] = useState<File | null>(null);
  const [isDragging, setIsDragging] = useState(false);
  const [isDecompressing, setIsDecompressing] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<DecompressionResult | null>(null);
  const [isCopied, setIsCopied] = useState(false);

  const fileInputRef = useRef<HTMLInputElement>(null);
  const { recordOperation } = useSessionStats();

  const handleDragOver = (e: DragEvent<HTMLDivElement>) => {
    e.preventDefault();
    setIsDragging(true);
  };

  const handleDragLeave = (e: DragEvent<HTMLDivElement>) => {
    e.preventDefault();
    setIsDragging(false);
  };

  const validateAndSetFile = (file: File) => {
    setError(null);
    setResult(null);

    // Validate .huf extension
    if (!file.name.toLowerCase().endsWith('.huf')) {
      setError('Please select a valid .huf archive file generated by Huffman Studio.');
      return;
    }

    setSelectedFile(file);
  };

  const handleDrop = (e: DragEvent<HTMLDivElement>) => {
    e.preventDefault();
    setIsDragging(false);
    if (e.dataTransfer.files && e.dataTransfer.files.length > 0) {
      validateAndSetFile(e.dataTransfer.files[0]);
    }
  };

  const handleFileChange = (e: ChangeEvent<HTMLInputElement>) => {
    if (e.target.files && e.target.files.length > 0) {
      validateAndSetFile(e.target.files[0]);
    }
  };

  const clearSelection = () => {
    setSelectedFile(null);
    setError(null);
    setResult(null);
    setIsCopied(false);
    if (fileInputRef.current) {
      fileInputRef.current.value = '';
    }
  };

  const handleDecompress = async () => {
    if (!selectedFile) return;

    setIsDecompressing(true);
    setError(null);

    try {
      const res = await decompressionService.decompressFile(selectedFile);
      setResult(res);

      recordOperation({
        type: 'DECOMPRESS',
        fileName: selectedFile.name,
        originalSize: res.blob.size,
        processedSize: selectedFile.size,
        ratio: res.stats?.compressionRatio,
        savingsPercent: res.stats?.percentageSaved,
      });
    } catch (err: unknown) {
      const errorMessage =
        err instanceof Error ? err.message : 'Failed to decompress archive. The file may be corrupt.';
      setError(errorMessage);
    } finally {
      setIsDecompressing(false);
    }
  };

  const handleCopyToClipboard = async () => {
    if (!result) return;
    try {
      await navigator.clipboard.writeText(result.text);
      setIsCopied(true);
      setTimeout(() => setIsCopied(false), 2000);
    } catch (err) {
      console.error('Failed to copy text: ', err);
    }
  };

  const handleDownloadText = () => {
    if (!result) return;
    decompressionService.downloadBlob(result.blob, result.filename);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="border-b border-slate-800 pb-4">
        <h2 className="text-2xl font-bold text-slate-100 flex items-center gap-2.5">
          <FileText className="w-6 h-6 text-emerald-400" />
          Archive Decompressor
        </h2>
        <p className="text-sm text-slate-400 mt-1">
          Upload previously generated <code className="text-emerald-400 font-mono">.huf</code> archives
          to reconstruct the exact original text with bit-for-bit CRC-32 validation.
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Left Column: Upload & Actions */}
        <div className="lg:col-span-2 space-y-6">
          <Card>
            {/* Hidden File Input */}
            <input
              type="file"
              ref={fileInputRef}
              onChange={handleFileChange}
              accept=".huf"
              className="hidden"
            />

            {!selectedFile ? (
              <div
                onDragOver={handleDragOver}
                onDragLeave={handleDragLeave}
                onDrop={handleDrop}
                onClick={() => fileInputRef.current?.click()}
                className={`border-2 border-dashed rounded-xl p-10 text-center cursor-pointer transition-all ${
                  isDragging
                    ? 'border-emerald-400 bg-emerald-500/10 scale-[1.01]'
                    : 'border-slate-700 hover:border-emerald-500/50 hover:bg-slate-900/40'
                }`}
              >
                <FileCheck
                  className={`w-12 h-12 mx-auto mb-3 transition-colors ${
                    isDragging ? 'text-emerald-400' : 'text-slate-500'
                  }`}
                />
                <h3 className="text-base font-semibold text-slate-200">
                  {isDragging ? 'Drop .huf archive here' : 'Select .huf archive to decompress'}
                </h3>
                <p className="text-xs text-slate-400 mt-1">
                  Reconstructs original tree topology and decodes stream with BitReader
                </p>
                <div className="mt-6">
                  <button
                    type="button"
                    className="px-5 py-2.5 rounded-lg text-sm font-semibold bg-emerald-600 hover:bg-emerald-500 text-white transition-colors shadow-lg shadow-emerald-900/30"
                  >
                    Select .huf File
                  </button>
                </div>
              </div>
            ) : (
              <div className="space-y-6">
                {/* File Details Bar */}
                <div className="flex items-center justify-between p-4 rounded-xl bg-slate-900/80 border border-slate-700/60">
                  <div className="flex items-center gap-3 min-w-0">
                    <div className="w-10 h-10 rounded-lg bg-emerald-500/10 border border-emerald-500/20 flex items-center justify-center text-emerald-400 shrink-0">
                      <FileCheck className="w-5 h-5" />
                    </div>
                    <div className="min-w-0">
                      <h4 className="text-sm font-semibold text-slate-100 truncate">
                        {selectedFile.name}
                      </h4>
                      <p className="text-xs text-slate-400 font-mono">
                        {formatBytes(selectedFile.size)} &bull; Huffman Binary Archive
                      </p>
                    </div>
                  </div>
                  <button
                    onClick={clearSelection}
                    disabled={isDecompressing}
                    className="p-1.5 rounded-lg text-slate-400 hover:text-rose-400 hover:bg-slate-800 transition-colors"
                    title="Remove file"
                  >
                    <X className="w-5 h-5" />
                  </button>
                </div>

                {/* Decompress Button */}
                <button
                  onClick={handleDecompress}
                  disabled={isDecompressing}
                  className="w-full py-3 px-4 rounded-xl text-sm font-bold bg-emerald-600 hover:bg-emerald-500 disabled:bg-slate-800 disabled:text-slate-500 disabled:cursor-not-allowed text-white transition-all flex items-center justify-center gap-2 shadow-lg shadow-emerald-900/30"
                >
                  {isDecompressing ? (
                    <>
                      <Loader2 className="w-4 h-4 animate-spin text-emerald-400" />
                      Decompressing Archive...
                    </>
                  ) : (
                    <>
                      <FileText className="w-4 h-4" />
                      Decompress Archive
                    </>
                  )}
                </button>
              </div>
            )}

            {/* Error Notification */}
            {error && (
              <div className="mt-4 p-4 rounded-xl bg-rose-950/40 border border-rose-800/60 flex items-start gap-3 text-xs text-rose-300">
                <AlertTriangle className="w-4 h-4 text-rose-400 shrink-0 mt-0.5" />
                <div className="space-y-1">
                  <span className="font-semibold text-rose-200">Decompression Failure</span>
                  <p className="leading-relaxed">{error}</p>
                </div>
              </div>
            )}
          </Card>

          {/* Results Card */}
          {result && (
            <Card
              title="Restored Content"
              subtitle={`Recovered from ${result.filename}`}
              headerAction={
                <div className="flex items-center gap-2">
                  <button
                    onClick={handleCopyToClipboard}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 transition-colors"
                  >
                    {isCopied ? (
                      <>
                        <Check className="w-3.5 h-3.5 text-emerald-400" />
                        <span className="text-emerald-400">Copied!</span>
                      </>
                    ) : (
                      <>
                        <Copy className="w-3.5 h-3.5" />
                        Copy Text
                      </>
                    )}
                  </button>
                  <button
                    onClick={handleDownloadText}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-emerald-600 hover:bg-emerald-500 text-white transition-colors"
                  >
                    <Download className="w-3.5 h-3.5" />
                    Download .txt
                  </button>
                </div>
              }
            >
              <div className="space-y-4">
                {/* Verification Stats Bar */}
                <div className="grid grid-cols-2 sm:grid-cols-3 gap-3">
                  <div className="p-3 rounded-lg bg-slate-900/60 border border-slate-700/50">
                    <span className="text-xs text-slate-400">Restored Size</span>
                    <p className="text-base font-mono font-bold text-slate-100 mt-0.5">
                      {formatBytes(result.blob.size)}
                    </p>
                  </div>
                  <div className="p-3 rounded-lg bg-slate-900/60 border border-slate-700/50">
                    <span className="text-xs text-slate-400">Unicode Characters</span>
                    <p className="text-base font-mono font-bold text-emerald-400 mt-0.5">
                      {result.text.length.toLocaleString()}
                    </p>
                  </div>
                  <div className="p-3 rounded-lg bg-slate-900/60 border border-slate-700/50 col-span-2 sm:col-span-1">
                    <span className="text-xs text-slate-400 flex items-center gap-1">
                      <ShieldCheck className="w-3.5 h-3.5 text-emerald-400" />
                      CRC-32 Integrity
                    </span>
                    <p className="text-base font-mono font-bold text-emerald-400 mt-0.5">
                      Verified Match
                    </p>
                  </div>
                </div>

                {/* Textarea Preview */}
                <div className="space-y-1.5">
                  <label className="text-xs font-semibold uppercase tracking-wider text-slate-400">
                    Original Text Preview
                  </label>
                  <textarea
                    readOnly
                    rows={12}
                    value={result.text}
                    className="w-full rounded-xl bg-slate-950 border border-slate-700/80 p-4 font-mono text-xs text-slate-200 leading-relaxed focus:outline-none focus:ring-1 focus:ring-emerald-500 resize-y"
                  />
                </div>
              </div>
            </Card>
          )}
        </div>

        {/* Right Column: Information & Verification */}
        <div className="space-y-6">
          <Card title="Integrity Guarantees" subtitle="Lossless Decompression">
            <div className="space-y-4 text-xs text-slate-300 leading-relaxed">
              <div className="flex items-start gap-3">
                <ShieldCheck className="w-5 h-5 text-emerald-400 shrink-0 mt-0.5" />
                <div>
                  <strong className="text-white">CRC-32 Verification:</strong>
                  <p className="text-slate-400 mt-0.5">
                    Before releasing the uncompressed text, the Java backend re-computes the CRC-32
                    hash of the decompressed bytes and verifies it against the 4-byte checksum
                    embedded in the header.
                  </p>
                </div>
              </div>

              <div className="flex items-start gap-3">
                <Hash className="w-5 h-5 text-emerald-400 shrink-0 mt-0.5" />
                <div>
                  <strong className="text-white">Topology Reconstruction:</strong>
                  <p className="text-slate-400 mt-0.5">
                    The serialized preorder tree bit sequence is traversed to rebuild the exact
                    canonical Huffman tree without requiring the original frequency table.
                  </p>
                </div>
              </div>

              <div className="flex items-start gap-3">
                <Cpu className="w-5 h-5 text-emerald-400 shrink-0 mt-0.5" />
                <div>
                  <strong className="text-white">Full Unicode Fidelity:</strong>
                  <p className="text-slate-400 mt-0.5">
                    Supports 1-to-4 byte UTF-8 sequences including full multi-lingual alphabets,
                    CJK, emojis, and symbols.
                  </p>
                </div>
              </div>
            </div>
          </Card>

          <Card title="Error Diagnostics" subtitle="Built-in Failure Modes">
            <div className="space-y-2 text-xs text-slate-400">
              <p>The backend rejects invalid archives with precise error codes:</p>
              <ul className="list-disc list-inside space-y-1 font-mono text-[11px] text-slate-300">
                <li><code className="text-rose-400">INVALID_ARCHIVE_MAGIC</code>: Not a .huf file</li>
                <li><code className="text-rose-400">UNSUPPORTED_VERSION</code>: Incompatible version</li>
                <li><code className="text-rose-400">CHECKSUM_MISMATCH</code>: File modified or corrupted</li>
                <li><code className="text-rose-400">CORRUPTED_ARCHIVE</code>: Truncated bitstream</li>
              </ul>
            </div>
          </Card>
        </div>
      </div>
    </div>
  );
};
